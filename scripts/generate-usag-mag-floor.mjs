import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const evidence = JSON.parse(
  fs.readFileSync(path.join(root, 'scripts/data/usag-mag-floor-elements.json'), 'utf8')
)
const output = path.join(root, 'backend/migrations/284_usag_mag_optional_floor_elements.sql')

const sql = (value) => `'${String(value).replaceAll("'", "''")}'`
const groupNames = {
  1: 'Non-acrobatic elements',
  2: 'Acrobatic elements forward',
  3: 'Acrobatic elements backward',
  4: 'Single saltos forward/backward with one or more turns',
}
const groupInstruction = {
  1: 'Establish the exact start support, move continuously into the declared strength, flexibility, circle, flair, roll, or handstand position, show every required 2-second hold, and exit without an unlisted support.',
  2: 'Create a forward-rising takeoff, show the declared number of saltos, shape, and twist, preserve direction, finish rotation before the floor, and land or reach front support exactly as listed.',
  3: 'Set upward from the backward entry, maintain the declared salto count, body shape, Arabian pathway, and twist distribution, open before contact, and finish on the prescribed landing or roll.',
  4: 'Create a vertical single-salto axis, complete the exact forward/backward rotation and longitudinal twist, maintain the listed body position, and land with chest and feet controlled.',
}

const rows = evidence.elements.map((element) => `    (${[
  sql(element.slug), element.group, element.number, sql(element.value), element.points,
  element.page, sql(element.description), sql(groupNames[element.group]),
  sql(groupInstruction[element.group]),
].join(', ')})`).join(',\n')

const content = `-- Generated by scripts/generate-usag-mag-floor.mjs.
-- Complete non-empty FIG 2025-2028 MAG Floor table used by USA Gymnastics
-- optional Levels 7-10: 96 individually numbered elements.

WITH source_data (
  slug, group_no, element_no, difficulty_letter, difficulty_points,
  source_page, official_description, group_name, instruction
) AS (
  VALUES
${rows}
),
prepared AS (
  SELECT d.*, jsonb_build_object(
    'governing_body','USA Gymnastics / FIG',
    'discipline','Men''s Artistic Gymnastics',
    'event','Floor Exercise',
    'program','Men''s Development Program 2025-2028 / FIG MAG Code 2025-2028',
    'official_name',d.official_description,
    'official_code','MAG FX EG ' || d.group_no || ' #' || lpad(d.element_no::text,3,'0'),
    'official_notation','EG' || d.group_no || '/' || lpad(d.element_no::text,3,'0') || ' ' || d.difficulty_letter,
    'usa_gymnastics_levels',jsonb_build_array('MAG Level 7','MAG Level 8','MAG Level 9','MAG Level 10'),
    'status','verified',
    'last_verified','2026-07-25',
    'prerequisites','[]'::jsonb,
    'next_progressions','[]'::jsonb,
    'athlete_cues',jsonb_build_array(
      d.instruction,
      'Know the exact element-group number and difficulty letter; closely related shapes, twists, and hold durations may be different elements.'
    ),
    'coach_checkpoints',jsonb_build_array(
      d.official_description,d.instruction,
      'Verify start/end position, support or flight, direction, body shape, salto/turn count, named-skill alternative, hold duration, and landing against the exact FIG box.',
      'For USA element-group credit, apply the current Men''s Development level threshold separately from the element''s FIG difficulty value.'
    ),
    'safety_and_readiness',jsonb_build_array(
      'Use a qualified men''s artistic coach, regulation sprung-floor progressions, pits and landing mats, appropriate spotting/belts, and an emergency action plan.',
      'Clear every strength shape, support, takeoff, timer, rotation/twist phase, opening, and landing independently before the complete element.',
      'High-difficulty multiple saltos, strength presses, Japanese handstands, and flair combinations require specialized readiness; a catalog level is not permission to attempt.'
    ),
    'common_faults',jsonb_build_array(
      jsonb_build_object('fault','Small execution error','deduction','0.1 each','cue','Correct minor line, precision, or landing deviation.'),
      jsonb_build_object('fault','Medium execution error','deduction','0.3 each','cue','Restore clear body position, amplitude, control, and technique.'),
      jsonb_build_object('fault','Large execution error','deduction','0.5 each','cue','Regress major bend, support, height, rotation, or landing failure.'),
      jsonb_build_object('fault','Fall','deduction','1.0','cue','Finish rotation and center of mass before landing/support.'),
      jsonb_build_object('fault','Hold shorter than required / element not recognizable','deduction','No recognition or value plus execution consequences','cue','Show the complete 2-second hold and exact defining characteristic.'),
      jsonb_build_object('fault','Step or touch outside floor boundary','deduction','0.1 each occurrence from final score','cue','Control direction and landing inside the marked area.'),
      jsonb_build_object('fault','Exercise longer than 70 seconds','deduction','0.1 neutral deduction','cue','Time from first movement.'),
      jsonb_build_object('fault','Non-permitted spotter on floor / assistance','deduction','-0.5 optional spotter presence / -1.0 assistance','cue','Keep coach outside the floor unless rules explicitly permit.')
    ),
    'scoring_summary','FIG value ' || d.difficulty_letter || ' = ' || to_char(d.difficulty_points,'FM0.0') || '. USA Gymnastics Levels 7-10 use modified FIG difficulty and element-group rules: current guidance requires A-level content at Levels 7/8, C for full EG II/III credit at Level 9, and D for full EG II/III credit at Level 10. Execution deductions are generally 0.1/0.3/0.5 and a fall is 1.0; neutral, boundary, time, and composition deductions apply.',
    'video_briefs',jsonb_build_array(
      jsonb_build_object('title','Learn MAG FX EG ' || d.group_no || ' #' || lpad(d.element_no::text,3,'0'),'purpose','learning','description','Open with the exact FIG box and value. Show prerequisite shapes, takeoff/support stations, progressive drills and spotting, the complete element, and safe landing/exit from side, end, overhead, and judging views.'),
      jsonb_build_object('title',d.official_description || ' - ideal MAG model','purpose','model','description','Show full speed and frame-by-frame with the EG/number/value overlay. Mark start, peak position or flight, support/hold time, salto and twist completion, body shape, amplitude, direction, and landing.')
    ),
    'sources',jsonb_build_array(
      jsonb_build_object('title','FIG Men''s Artistic Gymnastics Code of Points 2025-2028 - Floor Exercise','url','https://www.gymnastics.sport/publicdir/rules/files/en_1.1%20-%20MAG%20Code%20of%20Points%202025-2028.pdf#page=' || d.source_page,'organization','FIG / World Gymnastics','effective_cycle','2025-2028','accessed_on','2026-07-25','note','Official element group, numbered box, description, value, and Floor execution rules.'),
      jsonb_build_object('title','USA Gymnastics Men''s Development Program Rules','url','https://usagym.org/men/rules/','organization','USA Gymnastics','effective_cycle','2025-2028','accessed_on','2026-07-25','note','Current USA competition manual access, newsletters, interpretations, and FIG incorporation.'),
      jsonb_build_object('title','USA Gymnastics MDP Newsletter #5','url','https://static.usagym.org/PDFs/Men/devprogram/newsletters/2026_jan27.pdf','organization','USA Gymnastics','effective_cycle','2025-2028','accessed_on','2026-07-25','note','Current element recognition, 50% rule, Level 10 restrictions, and Floor clarifications.')
    ),
    'editorial_note','Original coaching instructions; the short official table label is retained for precise element identification.'
  ) metadata
  FROM source_data d
)
INSERT INTO coaching.skill (
  facility_id,name,slug,description,instructions,sport_id,skill_level,
  skill_kind,evaluation_mode,execution_max_score,assistance_note,
  is_published,visibility,official_metadata
)
SELECT
  (SELECT id FROM public.facility ORDER BY id LIMIT 1),
  'MAG FX EG' || p.group_no || ' #' || lpad(p.element_no::text,3,'0') || ' - ' || p.official_description,
  p.slug,p.official_description,p.instruction,
  (SELECT id FROM coaching.sport WHERE key='gymnastics'),
  CASE WHEN p.difficulty_points >= 0.7 THEN 'ELITE'::public.skill_level
       WHEN p.difficulty_points >= 0.4 THEN 'ADVANCED'::public.skill_level
       ELSE 'INTERMEDIATE'::public.skill_level END,
  'individual','execution',10,
  p.group_name || '; ' || p.difficulty_letter || ' (' || to_char(p.difficulty_points,'FM0.0') || ')',
  TRUE,'facility',p.metadata
FROM prepared p
ON CONFLICT (facility_id,slug) DO UPDATE SET
  name=EXCLUDED.name,description=EXCLUDED.description,instructions=EXCLUDED.instructions,
  sport_id=EXCLUDED.sport_id,skill_level=EXCLUDED.skill_level,skill_kind=EXCLUDED.skill_kind,
  evaluation_mode=EXCLUDED.evaluation_mode,execution_max_score=EXCLUDED.execution_max_score,
  assistance_note=EXCLUDED.assistance_note,is_published=EXCLUDED.is_published,
  visibility=EXCLUDED.visibility,official_metadata=EXCLUDED.official_metadata,updated_at=NOW();
`

fs.writeFileSync(output, content)
console.log(`Wrote ${evidence.elements.length} MAG floor cards to ${path.relative(root, output)}`)
